def render_html(snap, diff=None):
    view = build(snap, diff)
    host = snap["meta"].get("hostname", "host")
    host_esc = host.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")
    # single-pass substitution so data containing '@@JS@@' etc. can never be re-expanded
    parts = {"HOST": host_esc, "CSS": _read("report.css"), "JS": _read("report.js"), "DATA": _json_for_script(view)}
    return re.sub(r"@@(HOST|CSS|JS|DATA)@@", lambda m: parts[m.group(1)], PAGE)


