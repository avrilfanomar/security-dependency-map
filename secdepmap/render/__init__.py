def _dot_id(s):
    return '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ")


def render_dot(snap):
    v = build(snap)
    colors = {"critical": "#a3004c", "high": "#c8331b", "medium": "#b86e00", "low": "#2f6fb3"}
    L = ["digraph secdepmap {",
         '  rankdir=LR; node [shape=box, style=rounded, fontname=Helvetica, fontsize=10]; edge [color="#9aa4b2"];']
    for i, n in enumerate(v["map"]["nodes"]):
        L.append('  n%d [label=%s, color="%s"];' % (i, _dot_id(n["label"]), colors.get(n["risk"], "#6b7480")))
    for a, b, style in v["map"]["edges"]:
        L.append("  n%d -> n%d [style=%s];" % (a, b, style))
    L.append("}")
    return "\n".join(L) + "\n"


def render_mermaid(snap):
    v = build(snap)
    cls = {"critical": "crit", "high": "high", "medium": "med", "low": "low"}
    L = ["flowchart LR"]
    for i, n in enumerate(v["map"]["nodes"]):
        lab = re.sub(r'["\[\]{}()<>|]', " ", n["label"])[:48]
        L.append('  n%d["%s"]%s' % (i, lab, (":::" + cls[n["risk"]]) if n["risk"] in cls else ""))
    arrow = {"solid": "-->", "dashed": "-.->", "dotted": "-.->"}
    for a, b, style in v["map"]["edges"]:
        L.append("  n%d %s n%d" % (a, arrow.get(style, "-->"), b))
    L += ["  classDef crit stroke:#a3004c,stroke-width:2px", "  classDef high stroke:#c8331b,stroke-width:2px",
          "  classDef med stroke:#b86e00", "  classDef low stroke:#2f6fb3"]
    return "\n".join(L) + "\n"
