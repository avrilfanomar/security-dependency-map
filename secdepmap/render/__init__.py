def _md(s):
    return re.sub(r"([|`*_<>\[\]])", r"\\\1", str(s if s is not None else "")).replace("\n", " ")


def render_md(snap, diff=None):
    v = build(snap, diff)
    m = snap["meta"]
    L = ["# Security dependency map: %s" % _md(m["hostname"]), "",
         "Collected %s as **%s** with secdepmap %s%s." % (
             m["collected_at"], m["run_as"], m["tool_version"],
             (", online enrichment: " + ", ".join(m["online"])) if m.get("online") else " (offline)"), ""]
    sev = snap["summary"]["findings_by_severity"]
    L.append("**Findings:** " + " · ".join("%s %d" % (s, sev[s]) for s in SEVERITIES) + "  ")
    L.append("**Packages:** " + " · ".join("%s %d" % kv for kv in sorted(snap["summary"]["packages_by_ecosystem"].items())) + "  ")
    L.append("**Collectors:** " + " · ".join("%s=%s" % (k, c["status"]) for k, c in snap["collectors"].items()))
    notes = ["%s: %s" % (k, n) for k, c in snap["collectors"].items() for n in c.get("notes", [])]
    if notes:
        L += ["", "> Coverage notes: " + "; ".join(_md(n) for n in notes)]
    L += ["", "## Findings (medium and above)", ""]
    for f in snap["findings"]:
        if SEV_RANK[f["severity"]] > SEV_RANK["medium"]:
            continue
        L.append("### [%s] %s" % (f["severity"].upper(), _md(f["title"])))
        if f.get("detail"):
            L.append(_md(f["detail"]))
        if f.get("remediation"):
            L += ["", "**Fix:** " + _md(f["remediation"])]
        L.append("")
    low = [f for f in snap["findings"] if SEV_RANK[f["severity"]] > SEV_RANK["medium"]]
    if low:
        L += ["### Lower severity", ""] + ["- [%s] %s" % (f["severity"], _md(f["title"])) for f in low] + [""]
    L += ["## Sources", "", "| State | Source | Type | Operated by | Signed by | Packages |", "|---|---|---|---|---|---|"]
    for s in v["sources"]:
        L.append("| %s | %s | %s | %s | %s | %d |" % (
            "on" if s["enabled"] else "**off**", _md(s["label"]), _md(s["eco"]), _md(s["vendor"]),
            _md(", ".join(s["signers"]) or s["trust"] or "-"), s["packages"]))
    L += ["", "## Vendors and where they publish security information", ""]
    for x in v["vendors"]:
        if x["pseudo"]:
            continue
        L.append("- **%s** (%d pkgs)%s" % (_md(x["label"]), x["packages"], "" if x["kb"] else " - not in KB"))
        for k, u in sorted((x["links"] or {}).items()):
            L.append("  - %s: %s" % (_md(k.replace("_", " ")), "<%s>" % u if re.match(r"^https?://", u) else "(invalid link)"))
    L += ["", "## Network exposure (non-loopback)", "", "| Risk | Port | Bound | Service | Package | Source |", "|---|---|---|---|---|---|"]
    for x in v["exposure"]:
        if x["scope"] == "loopback":
            continue
        L.append("| %s | %s/%s | %s | %s | %s | %s |" % (
            x["risk"] or "-", x["proto"], x["port"], _md(x["scope"]), _md(x["service"]), _md(x["package"]), _md(x["source"])))
    return "\n".join(L) + "\n"


