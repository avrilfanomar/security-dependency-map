"""Report renderers: html (self-contained), md, dot, mermaid, json."""

from __future__ import annotations

import json
import os
import re

from ..model import SEV_RANK, SEVERITIES
from .view import build

HERE = os.path.dirname(os.path.abspath(__file__))


def _read(name):
    with open(os.path.join(HERE, name), encoding="utf-8") as fh:
        return fh.read()


def _json_for_script(obj):
    """JSON safe to embed inside <script type=application/json>.

    Package names, maintainers etc. are attacker-influenced strings, so
    '<' (covers '</script>' and '<!--'), '>' , '&' and the JS line separators
    are escaped as \\uXXXX. The script is never executed - it is parsed with JSON.parse.
    """
    s = json.dumps(obj, separators=(",", ":"), default=str, ensure_ascii=False)
    return (s.replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")
             .replace("\u2028", "\\u2028").replace("\u2029", "\\u2029"))


def render(fmt, snap, diff=None):
    if fmt == "json":
        return json.dumps(snap, indent=1, default=str)
    if fmt == "html":
        return render_html(snap, diff)
    if fmt == "md":
        return render_md(snap, diff)
    if fmt == "dot":
        return render_dot(snap)
    if fmt == "mermaid":
        return render_mermaid(snap)
    raise ValueError("unknown format " + fmt)


